-- 星维管理后台 V2A：组织、岗位与影子 RBAC。
-- 仅新增表和固定基础数据；不修改 admin_users，不改变现有 ADMIN/OPERATOR 登录授权。

CREATE TABLE xw_departments (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    code VARCHAR(16) NOT NULL,
    name VARCHAR(80) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    built_in BOOLEAN NOT NULL DEFAULT TRUE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    UNIQUE KEY uk_xw_department_code (code),
    UNIQUE KEY uk_xw_department_name (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='星维固定七大中心';

CREATE TABLE xw_positions (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    department_id BIGINT NOT NULL,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(80) NOT NULL,
    category VARCHAR(64) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    built_in BOOLEAN NOT NULL DEFAULT TRUE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    UNIQUE KEY uk_xw_position_code (code),
    KEY idx_xw_position_department (department_id, sort_order),
    CONSTRAINT fk_xw_position_department FOREIGN KEY (department_id)
        REFERENCES xw_departments (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='星维155岗位正式词库';

CREATE TABLE xw_rbac_roles (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    code VARCHAR(48) NOT NULL,
    name VARCHAR(80) NOT NULL,
    data_scope VARCHAR(32) NOT NULL DEFAULT 'DEPARTMENT',
    sort_order INT NOT NULL DEFAULT 0,
    built_in BOOLEAN NOT NULL DEFAULT TRUE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    UNIQUE KEY uk_xw_role_code (code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='星维影子RBAC角色';

CREATE TABLE xw_permissions (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    code VARCHAR(64) NOT NULL,
    name VARCHAR(100) NOT NULL,
    module_code VARCHAR(40) NOT NULL,
    built_in BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME(6) NOT NULL,
    UNIQUE KEY uk_xw_permission_code (code),
    KEY idx_xw_permission_module (module_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='星维后台权限点';

CREATE TABLE xw_role_permissions (
    role_id BIGINT NOT NULL,
    permission_id BIGINT NOT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_xw_role_permission_role FOREIGN KEY (role_id)
        REFERENCES xw_rbac_roles (id) ON DELETE CASCADE,
    CONSTRAINT fk_xw_role_permission_permission FOREIGN KEY (permission_id)
        REFERENCES xw_permissions (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='星维角色权限关联';

CREATE TABLE xw_admin_profiles (
    admin_user_id BIGINT NOT NULL,
    employee_no VARCHAR(32) NULL,
    display_name VARCHAR(80) NULL,
    department_id BIGINT NULL,
    position_id BIGINT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE',
    notes VARCHAR(500) NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (admin_user_id),
    UNIQUE KEY uk_xw_admin_employee_no (employee_no),
    KEY idx_xw_admin_profile_department (department_id),
    KEY idx_xw_admin_profile_position (position_id),
    CONSTRAINT fk_xw_admin_profile_user FOREIGN KEY (admin_user_id)
        REFERENCES admin_users (id) ON DELETE CASCADE,
    CONSTRAINT fk_xw_admin_profile_department FOREIGN KEY (department_id)
        REFERENCES xw_departments (id) ON DELETE SET NULL,
    CONSTRAINT fk_xw_admin_profile_position FOREIGN KEY (position_id)
        REFERENCES xw_positions (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='现有后台账号的星维员工档案扩展';

CREATE TABLE xw_admin_roles (
    admin_user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (admin_user_id, role_id),
    CONSTRAINT fk_xw_admin_role_user FOREIGN KEY (admin_user_id)
        REFERENCES admin_users (id) ON DELETE CASCADE,
    CONSTRAINT fk_xw_admin_role_role FOREIGN KEY (role_id)
        REFERENCES xw_rbac_roles (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='后台账号影子RBAC角色关联';

