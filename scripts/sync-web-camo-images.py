#!/usr/bin/env python3
"""Copy the reviewed mini-program's images to the web; never execute its JavaScript."""
import argparse
import json
import re
from pathlib import Path, PurePosixPath
import shutil

ROOT = Path(__file__).resolve().parents[1]
MINI = ROOT / 'wechat-mini/miniprogram'
STATIC = ROOT / 'src/main/resources/static'
MANIFEST = STATIC / 'assets/mw4-camo-images.js'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = (MINI / 'data/image-map.js').read_text(encoding='utf-8')
    literal = source.split('module.exports =', 1)[1].strip().rstrip(';')
    raw = json.loads(re.sub(r',\s*}', '\n}', literal))
    mapping = {}
    for remote, local in sorted(raw.items()):
        relative = PurePosixPath(local.lstrip('/'))
        if not remote.startswith('/assets/') or '..' in relative.parts or relative.parts[0] != 'images':
            raise ValueError('Unexpected image mapping')
        origin = MINI.joinpath(*relative.parts)
        target = STATIC / 'assets/mini-camo' / Path(*relative.parts[1:])
        if args.check:
            if not target.is_file() or target.read_bytes() != origin.read_bytes():
                raise SystemExit(f'Web image differs from mini-program: {relative}')
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(origin, target)
        mapping[remote] = '/' + target.relative_to(STATIC).as_posix()
    output = '// Generated by scripts/sync-web-camo-images.py; source: mini-program image-map.\n'
    output += 'window.XinghuoCamoImages = Object.freeze(' + json.dumps(mapping, ensure_ascii=False, indent=2) + ');\n'
    if args.check:
        if not MANIFEST.is_file() or MANIFEST.read_text(encoding='utf-8') != output:
            raise SystemExit('Web camo image map is stale')
    else:
        MANIFEST.write_text(output, encoding='utf-8')
    print(f'Web camo images {"verified" if args.check else "synchronized"}: {len(mapping)}')


if __name__ == '__main__':
    main()
