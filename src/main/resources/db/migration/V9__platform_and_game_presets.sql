CREATE TABLE IF NOT EXISTS platform_catalog (
  code VARCHAR(32) PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  description VARCHAR(240) NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS game_platforms (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  game_code VARCHAR(32) NOT NULL,
  platform_code VARCHAR(32) NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_game_platform UNIQUE (game_code, platform_code),
  CONSTRAINT fk_game_platform_game FOREIGN KEY (game_code) REFERENCES game_catalog(code) ON DELETE CASCADE,
  CONSTRAINT fk_game_platform_platform FOREIGN KEY (platform_code) REFERENCES platform_catalog(code) ON DELETE RESTRICT
);
CREATE INDEX idx_game_platform_game ON game_platforms(game_code, is_active, sort_order);
CREATE INDEX idx_game_platform_platform ON game_platforms(platform_code, is_active);

